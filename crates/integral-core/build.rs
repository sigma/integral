//! Build script: generates `factory_catalog.rs` from `docs/sounds/*.json`,
//! the Wave catalog from `docs/waves/*.json`, the SN Drum Inst list from
//! `docs/sn-drum-insts/insts.json`, the SN Acoustic instrument list from
//! `docs/sn-acoustic-insts/insts.json`, the Foreign Wave map from
//! `docs/research/jv-wave-map.json`, and the Foreign effect map from
//! `docs/research/foreign-fx-map.json`.

use std::collections::{BTreeMap, HashMap};
use std::fs;
use std::io::Write;
use std::path::Path;

#[derive(serde::Deserialize)]
struct SoundEntry {
    name: String,
    msb: u8,
    lsb: u8,
    pc: u8,
    #[serde(default)]
    category: Option<String>,
}

#[derive(serde::Deserialize)]
struct WaveEntry {
    number: u16,
    name: String,
}

/// One Inst of `docs/sn-drum-insts/insts.json` (the fields the build reads).
#[derive(serde::Deserialize)]
struct SndInstEntry {
    number: u16,
    name: String,
    #[serde(rename = "type")]
    family: String,
    bank: String,
    /// The Variations the Inst supports: absent, `Flam/Buzz` or `Flam/Buzz/Roll`.
    #[serde(default)]
    vari: Option<String>,
}

/// One instrument of `docs/sn-acoustic-insts/insts.json` (the fields the build reads).
#[derive(serde::Deserialize)]
struct SnaInstEntry {
    number: u16,
    name: String,
    category: String,
    bank: String,
    lsb: u8,
    pc: u8,
    /// `[slot, name]` of each Modify Parameter, where Roland's Editor names them.
    modify: Vec<(u8, String)>,
}

/// Generate `SNA_INSTS` from the SN Acoustic instrument list: numbers run 1…N
/// and each (lsb, pc) pair names one instrument.
fn generate_sn_acoustic_insts(path: &Path, out_dir: &Path) {
    println!("cargo::rerun-if-changed={}", path.display());
    let content = fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()));
    let entries: Vec<SnaInstEntry> = serde_json::from_str(&content)
        .unwrap_or_else(|e| panic!("failed to parse {}: {e}", path.display()));
    let mut seen = std::collections::HashSet::new();
    let mut out = fs::File::create(out_dir.join("sn_acoustic_inst_data.rs"))
        .expect("failed to create SN Acoustic instrument output");
    writeln!(out, "// Generated by build.rs — do not edit.").unwrap();
    writeln!(out, "const SNA_INSTS: &[SnaInst] = &[").unwrap();
    for (i, e) in entries.iter().enumerate() {
        assert_eq!(
            usize::from(e.number),
            i + 1,
            "sn-acoustic insts.json: numbers must run 1…N"
        );
        assert!(
            seen.insert((e.lsb, e.pc)),
            "sn-acoustic insts.json: ({}, {}) twice",
            e.lsb,
            e.pc
        );
        writeln!(
            out,
            "    SnaInst {{ number: {}, name: {:?}, category: {:?}, bank: {:?}, variation: {}, inst_number: {}, modify: &{:?} }},",
            e.number, e.name, e.category, e.bank, e.lsb, e.pc, e.modify
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
}

/// Generate `SND_INSTS` from the SN Drum Inst list: Inst Numbers must run 1…N.
fn generate_sn_drum_insts(path: &Path, out_dir: &Path) {
    println!("cargo::rerun-if-changed={}", path.display());
    let content = fs::read_to_string(path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()));
    let entries: Vec<SndInstEntry> = serde_json::from_str(&content)
        .unwrap_or_else(|e| panic!("failed to parse {}: {e}", path.display()));
    let mut out = fs::File::create(out_dir.join("sn_drum_inst_data.rs"))
        .expect("failed to create SN Drum Inst output");
    writeln!(out, "// Generated by build.rs — do not edit.").unwrap();
    writeln!(out, "const SND_INSTS: &[SndInst] = &[").unwrap();
    for (i, e) in entries.iter().enumerate() {
        assert_eq!(
            usize::from(e.number),
            i + 1,
            "insts.json: Inst Numbers must run 1…N"
        );
        // The Variation families the Inst supports, from `Flam/Buzz/Roll`-style lists.
        let mut families = [false; 3];
        for family in e.vari.iter().flat_map(|v| v.split('/')) {
            let i = ["Flam", "Buzz", "Roll"]
                .iter()
                .position(|&f| f == family)
                .unwrap_or_else(|| {
                    panic!(
                        "insts.json: Inst {} has unknown Variation {family}",
                        e.number
                    )
                });
            families[i] = true;
        }
        let [flam, buzz, roll] = families;
        writeln!(
            out,
            "    SndInst {{ number: {}, name: {:?}, family: {:?}, bank: {:?}, \
             variations: SndVariations {{ flam: {flam}, buzz: {buzz}, roll: {roll} }} }},",
            e.number, e.name, e.family, e.bank
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
}

/// One source Wave of `docs/research/jv-wave-map.json`.
#[derive(serde::Deserialize)]
struct ForeignWaveEntry {
    number: u16,
    name: String,
    target: Option<ForeignWaveTarget>,
    confidence: String,
}

/// Where a Foreign Wave lands on the INTEGRA-7.
#[derive(serde::Deserialize)]
struct ForeignWaveTarget {
    /// `INT` or `SRX-01`…`SRX-12`.
    group: String,
    number: u16,
    name: String,
}

/// The part of `docs/research/jv-wave-map.json` the build reads.
#[derive(serde::Deserialize)]
struct ForeignWaveMap {
    waves: BTreeMap<String, Vec<ForeignWaveEntry>>,
}

/// One parameter row of a JV EFX type in `foreign-fx-map.json`.
#[derive(serde::Deserialize)]
struct EffectParamEntry {
    jv_prm: u8,
    jv_name: String,
    conv: String,
    #[serde(default)]
    integra_params: Vec<u8>,
    sync_sw_param: Option<u8>,
    note_param: Option<u8>,
    neutral: Option<u8>,
}

/// An Integra parameter with no source, and the value it gets.
#[derive(serde::Deserialize)]
struct EffectUnmappedEntry {
    n: u8,
    value: i32,
}

/// One JV EFX type of `foreign-fx-map.json`.
#[derive(serde::Deserialize)]
struct JvEffectEntry {
    jv_display: u8,
    name: String,
    class: String,
    integra_type: Option<u8>,
    params: Vec<EffectParamEntry>,
    #[serde(default)]
    integra_unmapped: Vec<EffectUnmappedEntry>,
}

/// One XV MFX type 41–90 of `foreign-fx-map.json`.
#[derive(serde::Deserialize)]
struct XvEffectEntry {
    xv_type: u8,
    name: String,
    class: String,
    /// The Integra type, led by its number (`9 PHASER 1 …`), or `-`.
    integra: String,
    /// The Integra MFX Parameter each XV Parameter 1… copies to, for the
    /// types whose layout the corpus and the manual support.
    #[serde(default)]
    copy_slots: Vec<u8>,
}

/// The part of `docs/research/foreign-fx-map.json` the build reads.
#[derive(serde::Deserialize)]
struct ForeignFxMap {
    jv_efx: Vec<JvEffectEntry>,
    xv_mfx_41_90: Vec<XvEffectEntry>,
}

/// Wave Group files and the identifier of the generated array, in
/// `WaveGroup::ALL` order.
const WAVE_FILES: [(&str, &str); 14] = [
    ("int.json", "WAVES_INT"),
    ("srx-01.json", "WAVES_SRX_01"),
    ("srx-02.json", "WAVES_SRX_02"),
    ("srx-03.json", "WAVES_SRX_03"),
    ("srx-04.json", "WAVES_SRX_04"),
    ("srx-05.json", "WAVES_SRX_05"),
    ("srx-06.json", "WAVES_SRX_06"),
    ("srx-07.json", "WAVES_SRX_07"),
    ("srx-08.json", "WAVES_SRX_08"),
    ("srx-09.json", "WAVES_SRX_09"),
    ("srx-10.json", "WAVES_SRX_10"),
    ("srx-11.json", "WAVES_SRX_11"),
    ("srx-12.json", "WAVES_SRX_12"),
    ("sn-synth.json", "WAVES_SN_SYNTH"),
];

/// Read the `File | Wave Group | Count` table of `docs/waves/README.md`.
fn load_wave_counts(readme: &Path) -> HashMap<String, usize> {
    println!("cargo::rerun-if-changed={}", readme.display());
    let content = fs::read_to_string(readme)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", readme.display()));
    content
        .lines()
        .filter_map(|line| {
            let cells: Vec<&str> = line.split('|').map(str::trim).collect();
            // `| file | group | count |` splits into 5 cells, the outer two empty.
            let [_, file, _, count, _] = cells.as_slice() else {
                return None;
            };
            let file = file.strip_prefix('`')?.strip_suffix('`')?;
            Some((file.to_string(), count.parse().ok()?))
        })
        .collect()
}

/// Generate `wave_catalog_data.rs`, checking each file against the README
/// counts and its numbers against 1…N. Returns each group's Wave names, keyed
/// by file name.
fn generate_waves(waves_dir: &Path, out_dir: &Path) -> HashMap<&'static str, Vec<String>> {
    let mut names = HashMap::new();
    let counts = load_wave_counts(&waves_dir.join("README.md"));
    let mut out = fs::File::create(out_dir.join("wave_catalog_data.rs"))
        .expect("failed to create wave output");
    writeln!(out, "// Generated by build.rs — do not edit.").unwrap();

    for (file, ident) in WAVE_FILES {
        let path = waves_dir.join(file);
        println!("cargo::rerun-if-changed={}", path.display());
        let content = fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()));
        let entries: Vec<WaveEntry> = serde_json::from_str(&content)
            .unwrap_or_else(|e| panic!("failed to parse {}: {e}", path.display()));

        let expected = counts
            .get(file)
            .unwrap_or_else(|| panic!("{file} missing from docs/waves/README.md"));
        assert_eq!(
            entries.len(),
            *expected,
            "{file}: {} Waves, README says {expected}",
            entries.len()
        );
        for (i, entry) in entries.iter().enumerate() {
            assert_eq!(
                usize::from(entry.number),
                i + 1,
                "{file}: Wave Numbers must run 1…N"
            );
        }

        writeln!(out, "const {ident}: &[Wave] = &[").unwrap();
        for entry in &entries {
            writeln!(
                out,
                "    Wave {{ number: {}, name: {:?} }},",
                entry.number, entry.name
            )
            .unwrap();
        }
        writeln!(out, "];").unwrap();
        names.insert(file, entries.into_iter().map(|e| e.name).collect());
    }
    names
}

/// The `ForeignWaveGroup` expression of a source group key of the Wave map:
/// `JV-INT-A`, `JV-INT-B` or `SR-JV80-nn`.
fn foreign_group(key: &str) -> String {
    match key {
        "JV-INT-A" => "ForeignWaveGroup::JvIntA".to_string(),
        "JV-INT-B" => "ForeignWaveGroup::JvIntB".to_string(),
        _ => {
            let board: u8 = key
                .strip_prefix("SR-JV80-")
                .and_then(|n| n.parse().ok())
                .unwrap_or_else(|| panic!("jv-wave-map.json: unknown source group {key}"));
            format!("ForeignWaveGroup::SrJv80({board})")
        }
    }
}

/// The `WaveGroup` expression of a target group of the Wave map, and the
/// `docs/waves` file that lists it.
fn target_group(group: &str) -> (String, String) {
    let file = format!("{}.json", group.to_lowercase());
    if group == "INT" {
        return ("WaveGroup::Int".to_string(), file);
    }
    let board: u8 = group
        .strip_prefix("SRX-")
        .and_then(|n| n.parse().ok())
        .filter(|n| (1..=12).contains(n))
        .unwrap_or_else(|| panic!("jv-wave-map.json: unknown target group {group}"));
    (format!("WaveGroup::Srx({board})"), file)
}

/// Generate `foreign_wave_map_data.rs` from `jv-wave-map.json`: one table
/// per source group, indexed by Wave Number − 1. Every target is checked
/// against the Wave catalog by number and name.
fn generate_foreign_wave_map(
    map_path: &Path,
    catalog: &HashMap<&'static str, Vec<String>>,
    out_dir: &Path,
) {
    println!("cargo::rerun-if-changed={}", map_path.display());
    let content = fs::read_to_string(map_path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", map_path.display()));
    let map: ForeignWaveMap = serde_json::from_str(&content)
        .unwrap_or_else(|e| panic!("failed to parse {}: {e}", map_path.display()));
    let mut out = fs::File::create(out_dir.join("foreign_wave_map_data.rs"))
        .expect("failed to create Foreign Wave map output");
    writeln!(out, "// Generated by build.rs — do not edit.").unwrap();

    let mut arms = Vec::new();
    for (key, entries) in &map.waves {
        let ident = format!("MAP_{}", key.replace('-', "_"));
        writeln!(out, "const {ident}: &[SourceWave] = &[").unwrap();
        for (i, entry) in entries.iter().enumerate() {
            assert_eq!(
                usize::from(entry.number),
                i + 1,
                "jv-wave-map.json {key}: Wave Numbers must run 1…N"
            );
            let target = match (&entry.target, entry.confidence.as_str()) {
                (None, "none") => "None".to_string(),
                (Some(t), confidence @ ("high" | "medium" | "low")) => {
                    let (group, file) = target_group(&t.group);
                    let names = catalog
                        .get(file.as_str())
                        .unwrap_or_else(|| panic!("no Wave catalog for {}", t.group));
                    assert_eq!(
                        names.get(usize::from(t.number).wrapping_sub(1)),
                        Some(&t.name),
                        "jv-wave-map.json {key} {}: target {} {} is not in the catalog",
                        entry.number,
                        t.group,
                        t.number
                    );
                    let confidence = match confidence {
                        "high" => "High",
                        "medium" => "Medium",
                        _ => "Low",
                    };
                    format!(
                        "Some(WaveTarget {{ group: {group}, number: {}, confidence: Confidence::{confidence} }})",
                        t.number
                    )
                }
                (_, confidence) => panic!(
                    "jv-wave-map.json {key} {}: confidence {confidence} does not fit the target",
                    entry.number
                ),
            };
            writeln!(
                out,
                "    SourceWave {{ name: {:?}, target: {target} }},",
                entry.name
            )
            .unwrap();
        }
        writeln!(out, "];").unwrap();
        arms.push((foreign_group(key), ident));
    }

    writeln!(
        out,
        "/// The Wave map of `group`, indexed by Wave Number − 1; empty for a group with no Wave list."
    )
    .unwrap();
    writeln!(
        out,
        "fn source_waves(group: ForeignWaveGroup) -> &'static [SourceWave] {{"
    )
    .unwrap();
    writeln!(out, "    match group {{").unwrap();
    for (group, ident) in arms {
        writeln!(out, "        {group} => {ident},").unwrap();
    }
    writeln!(out, "        _ => &[],").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();
}

/// The `Class` expression of a class name of the effect map.
fn effect_class(class: &str) -> &'static str {
    match class {
        "same" => "Class::Same",
        "rescaled" => "Class::Rescaled",
        "rescaled-lossy" => "Class::RescaledLossy",
        "substitute" => "Class::Substitute",
        "none" => "Class::None",
        _ => panic!("foreign-fx-map.json: unknown class {class}"),
    }
}

/// The `Conv` variant of a conversion code: `delay500_jv` → `Delay500Jv`.
fn effect_conv(code: &str) -> String {
    code.split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// The leading Integra type number of an XV 41–90 target (`9 PHASER 1`,
/// `53/54/56 GTAMPSIM …`), or `None` for `-`.
fn leading_number(integra: &str) -> Option<u8> {
    let digits: String = integra.chars().take_while(char::is_ascii_digit).collect();
    (!digits.is_empty()).then(|| digits.parse().expect("a type number"))
}

/// Generate `foreign_fx_map_data.rs` from `foreign-fx-map.json`: the 40 JV
/// EFX types with their parameter rows, and the targets of XV MFX 41–90.
fn generate_foreign_fx_map(map_path: &Path, out_dir: &Path) {
    println!("cargo::rerun-if-changed={}", map_path.display());
    let content = fs::read_to_string(map_path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", map_path.display()));
    let map: ForeignFxMap = serde_json::from_str(&content)
        .unwrap_or_else(|e| panic!("failed to parse {}: {e}", map_path.display()));
    let mut out = fs::File::create(out_dir.join("foreign_fx_map_data.rs"))
        .expect("failed to create Foreign effect map output");
    writeln!(out, "// Generated by build.rs — do not edit.").unwrap();

    let opt = |v: Option<u8>| v.map_or("None".to_string(), |v| format!("Some({v})"));
    writeln!(out, "static JV_EFX: [JvEffect; {}] = [", map.jv_efx.len()).unwrap();
    for (i, t) in map.jv_efx.iter().enumerate() {
        assert_eq!(
            usize::from(t.jv_display),
            i + 1,
            "foreign-fx-map.json: JV EFX types must run 1…N"
        );
        assert_eq!(
            t.integra_type.is_none(),
            t.class == "none",
            "foreign-fx-map.json: JV EFX {} has a target iff its class is not none",
            t.jv_display
        );
        writeln!(
            out,
            "    JvEffect {{ name: {:?}, class: {}, target: {}, rows: &[",
            t.name,
            effect_class(&t.class),
            t.integra_type.unwrap_or(0)
        )
        .unwrap();
        for r in &t.params {
            writeln!(
                out,
                "        ParamRow {{ from: {}, name: {:?}, conv: Conv::{}, to: &{:?}, sync: {}, note: {}, neutral: {} }},",
                r.jv_prm,
                r.jv_name,
                effect_conv(&r.conv),
                r.integra_params,
                opt(r.sync_sw_param),
                opt(r.note_param),
                opt(r.neutral),
            )
            .unwrap();
        }
        let unmapped: Vec<String> = t
            .integra_unmapped
            .iter()
            .map(|u| format!("({}, {})", u.n, u.value))
            .collect();
        writeln!(out, "    ], unmapped: &[{}] }},", unmapped.join(", ")).unwrap();
    }
    writeln!(out, "];").unwrap();

    writeln!(
        out,
        "static XV_MFX: [XvEffect; {}] = [",
        map.xv_mfx_41_90.len()
    )
    .unwrap();
    for (i, t) in map.xv_mfx_41_90.iter().enumerate() {
        assert_eq!(
            usize::from(t.xv_type),
            i + 41,
            "foreign-fx-map.json: XV MFX types must run 41…90"
        );
        let target = leading_number(&t.integra);
        assert_eq!(
            target.is_none(),
            t.class == "none",
            "foreign-fx-map.json: XV MFX {} has a target iff its class is not none",
            t.xv_type
        );
        writeln!(
            out,
            "    XvEffect {{ name: {:?}, class: {}, target: {}, copy: &{:?} }},",
            t.name,
            effect_class(&t.class),
            target.unwrap_or(0),
            t.copy_slots
        )
        .unwrap();
    }
    writeln!(out, "];").unwrap();
}

/// Load the category name → numeric value mapping from `docs/sounds/categories.json`.
fn load_category_map(sounds_dir: &Path) -> HashMap<String, u8> {
    let cat_path = sounds_dir.join("categories.json");
    println!("cargo::rerun-if-changed={}", cat_path.display());

    let content = fs::read_to_string(&cat_path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", cat_path.display()));
    let raw: HashMap<String, String> = serde_json::from_str(&content)
        .unwrap_or_else(|e| panic!("failed to parse {}: {e}", cat_path.display()));

    let mut map: HashMap<String, u8> = raw
        .into_iter()
        .map(|(k, v)| {
            let num: u8 = k
                .parse()
                .unwrap_or_else(|_| panic!("invalid category key: {k}"));
            (v, num)
        })
        .collect();

    // Aliases from the sound list PDF (different spelling).
    map.insert("Drum".to_string(), 46);
    map
}

fn main() {
    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let sounds_dir = Path::new(&manifest_dir).join("../../docs/sounds");
    let out_dir = std::env::var("OUT_DIR").unwrap();
    let catalog = generate_waves(
        &Path::new(&manifest_dir).join("../../docs/waves"),
        Path::new(&out_dir),
    );
    generate_sn_drum_insts(
        &Path::new(&manifest_dir).join("../../docs/sn-drum-insts/insts.json"),
        Path::new(&out_dir),
    );
    generate_sn_acoustic_insts(
        &Path::new(&manifest_dir).join("../../docs/sn-acoustic-insts/insts.json"),
        Path::new(&out_dir),
    );
    generate_foreign_wave_map(
        &Path::new(&manifest_dir).join("../../docs/research/jv-wave-map.json"),
        &catalog,
        Path::new(&out_dir),
    );
    generate_foreign_fx_map(
        &Path::new(&manifest_dir).join("../../docs/research/foreign-fx-map.json"),
        Path::new(&out_dir),
    );
    let out_path = Path::new(&out_dir).join("factory_catalog_data.rs");

    let cat_map = load_category_map(&sounds_dir);

    // Collect all entries grouped by (msb, lsb).
    // (pc, name, category_value)
    type BankEntries = Vec<(u8, String, u8)>;
    let mut banks: BTreeMap<(u8, u8), BankEntries> = BTreeMap::new();

    let json_files = [
        "sn-acoustic-preset.json",
        "sn-synth-preset.json",
        "sn-drum-preset.json",
        "pcm-synth-preset.json",
        "pcm-drum-preset.json",
        "gm2.json",
        "exsn.json",
        "expcm.json",
    ];

    for filename in &json_files {
        let path = sounds_dir.join(filename);
        if !path.exists() {
            continue;
        }
        println!("cargo::rerun-if-changed={}", path.display());

        let content = fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()));
        let entries: Vec<SoundEntry> = serde_json::from_str(&content)
            .unwrap_or_else(|e| panic!("failed to parse {}: {e}", path.display()));

        for entry in entries {
            let cat_val = entry
                .category
                .as_deref()
                .and_then(|c| cat_map.get(c).copied())
                .unwrap_or(0);

            // PC is 1-indexed in JSON, convert to 0-indexed for MIDI.
            let pc = entry.pc.saturating_sub(1);

            banks
                .entry((entry.msb, entry.lsb))
                .or_default()
                .push((pc, entry.name, cat_val));
        }
    }

    // Sort entries within each bank by PC.
    for tones in banks.values_mut() {
        tones.sort_by_key(|t| t.0);
    }

    // Generate Rust source.
    let mut out = fs::File::create(&out_path).expect("failed to create output file");

    writeln!(out, "// Generated by build.rs — do not edit.").unwrap();
    writeln!(out).unwrap();

    // Emit one const array per bank.
    for ((msb, lsb), tones) in &banks {
        let ident = format!("BANK_{msb}_{lsb}");
        writeln!(out, "const {ident}: &[FactoryTone] = &[",).unwrap();
        for (pc, name, cat) in tones {
            // Escape any quotes in names.
            let escaped = name.replace('\\', "\\\\").replace('"', "\\\"");
            writeln!(
                out,
                "    FactoryTone {{ msb: {msb}, lsb: {lsb}, pc: {pc}, name: \"{escaped}\", category: {cat} }},",
            )
            .unwrap();
        }
        writeln!(out, "];").unwrap();
        writeln!(out).unwrap();
    }

    // Emit the lookup function.
    writeln!(
        out,
        "/// Look up factory tones for a given bank (MSB, LSB)."
    )
    .unwrap();
    writeln!(out, "///").unwrap();
    writeln!(
        out,
        "/// Returns a static slice of tones, or an empty slice for user/unknown banks."
    )
    .unwrap();
    writeln!(
        out,
        "pub fn factory_tones(msb: u8, lsb: u8) -> &'static [FactoryTone] {{"
    )
    .unwrap();
    writeln!(out, "    match (msb, lsb) {{").unwrap();
    for (msb, lsb) in banks.keys() {
        let ident = format!("BANK_{msb}_{lsb}");
        writeln!(out, "        ({msb}, {lsb}) => {ident},").unwrap();
    }
    writeln!(out, "        _ => &[],").unwrap();
    writeln!(out, "    }}").unwrap();
    writeln!(out, "}}").unwrap();

    // Total count for documentation.
    let total: usize = banks.values().map(|v| v.len()).sum();
    eprintln!(
        "factory_catalog: generated {} tones across {} banks",
        total,
        banks.len()
    );

    // -----------------------------------------------------------------------
    // Generate tone_category_data.rs (for svd.rs)
    // -----------------------------------------------------------------------

    let cat_data_path = Path::new(&out_dir).join("tone_category_data.rs");
    let mut cat_out = fs::File::create(&cat_data_path).expect("failed to create category output");

    writeln!(cat_out, "// Generated by build.rs — do not edit.").unwrap();
    writeln!(cat_out).unwrap();

    // Re-read the categories JSON for the forward mapping (value → name).
    let cat_json_path = sounds_dir.join("categories.json");
    let cat_content = fs::read_to_string(&cat_json_path).unwrap();
    let cat_entries: BTreeMap<u8, String> = {
        let raw: BTreeMap<String, String> = serde_json::from_str(&cat_content).unwrap();
        raw.into_iter()
            .map(|(k, v)| (k.parse::<u8>().unwrap(), v))
            .collect()
    };

    writeln!(
        cat_out,
        "/// Return the human-readable name for a tone category value."
    )
    .unwrap();
    writeln!(cat_out, "///").unwrap();
    writeln!(cat_out, "/// Generated from `docs/sounds/categories.json`.").unwrap();
    writeln!(
        cat_out,
        "pub fn tone_category_name(value: u8) -> Option<&'static str> {{"
    )
    .unwrap();
    writeln!(cat_out, "    match value {{").unwrap();
    for (val, name) in &cat_entries {
        writeln!(cat_out, "        {val} => Some(\"{name}\"),").unwrap();
    }
    writeln!(cat_out, "        _ => None,").unwrap();
    writeln!(cat_out, "    }}").unwrap();
    writeln!(cat_out, "}}").unwrap();
}
