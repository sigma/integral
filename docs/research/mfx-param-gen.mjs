// Generate the per-type MFX parameter tables of
// crates/integral-core/src/mfx_params.rs from Roland's INTEGRA-7 Editor model.
// See docs/research/mfx-param-layout.md.
//
// Usage (from the repo root):
//   node docs/research/mfx-param-gen.mjs crates/integral-core/src/mfx_params.rs
//   rustfmt --edition 2024 crates/integral-core/src/mfx_params.rs
//
// It replaces the text between the BEGIN/END GENERATED markers in that file.
// Roland's files are fetched from a pinned commit and run as-is in a `vm`
// context, so their own code builds the tables (no parsing). Each param's
// Parameter family is emitted as a bare `ParameterFamily` variant, which
// mfx_params.rs imports.
import fs from "node:fs";
import vm from "node:vm";

const MODEL =
  "https://raw.githubusercontent.com/SambaGodschynski/integra7-editor-web/d5b9193874e2a0e3261a231562dff856c685f9fe/js/model/";
const BEGIN = "// BEGIN GENERATED by docs/research/mfx-param-gen.mjs";
const END = "// END GENERATED";

const g = {
  model: { option: {} },
  parameter: { wave: { snSynth: [] } },
  log: () => {},
};
const ctx = {
  window: { globals: g },
  model_excmap_bank: function (t) {
    this.table = t;
  },
};
vm.createContext(ctx);
for (const f of ["model_excmap_mfx.js", "model_stringer.js"]) {
  const res = await fetch(MODEL + f);
  if (!res.ok) throw new Error(`${f}: HTTP ${res.status}`);
  vm.runInContext(await res.text(), ctx);
}
const S = g.model.stringer,
  T = g.model.option.mfx.table;
/** `MFX_34_DELAY` from type 34, Roland name `DELAY`. */
const constName = (id) =>
  `MFX_${String(id).padStart(2, "0")}_${T[id].desc
    .toUpperCase()
    .split(/[^A-Z0-9]+/)
    .filter(Boolean)
    .join("_")}`;

