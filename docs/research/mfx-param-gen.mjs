// Generate the per-type MFX parameter tables of
// crates/integral-core/src/mfx_params.rs from Roland's INTEGRA-7 Editor model.
// See docs/research/mfx-param-layout.md.
//
// Usage (from the repo root):
//   node docs/research/mfx-param-gen.mjs crates/integral-core/src/mfx_params.rs
//   rustfmt --edition 2024 crates/integral-core/src/mfx_params.rs
//
// It replaces the text between the BEGIN/END GENERATED markers in that file.
// Roland's files are fetched from a pinned commit and run as-is in a `vm`
// context, so their own code builds the tables (no parsing).
import fs from "node:fs";
import vm from "node:vm";

const MODEL =
  "https://raw.githubusercontent.com/SambaGodschynski/integra7-editor-web/d5b9193874e2a0e3261a231562dff856c685f9fe/js/model/";
const BEGIN = "// BEGIN GENERATED by docs/research/mfx-param-gen.mjs";
const END = "// END GENERATED";

const g = {
  model: { option: {} },
  parameter: { wave: { snSynth: [] } },
  log: () => {},
};
const ctx = {
  window: { globals: g },
  model_excmap_bank: function (t) {
    this.table = t;
  },
};
vm.createContext(ctx);
for (const f of ["model_excmap_mfx.js", "model_stringer.js"]) {
  const res = await fetch(MODEL + f);
  if (!res.ok) throw new Error(`${f}: HTTP ${res.status}`);
  vm.runInContext(await res.text(), ctx);
}
const S = g.model.stringer,
  T = g.model.option.mfx.table;
/** `MFX_34_DELAY` from type 34, Roland name `DELAY`. */
const constName = (id) =>
  `MFX_${String(id).padStart(2, "0")}_${T[id].desc
    .toUpperCase()
    .split(/[^A-Z0-9]+/)
    .filter(Boolean)
    .join("_")}`;

// The candidates below mirror FxUnit::format in fx_params.rs, to pick the unit
// whose output matches Roland's display string for every stored value.
const NOTE =
  "1/64T 1/64 1/32T 1/32 1/16T 1/32. 1/16 1/8T 1/16. 1/8 1/4T 1/8. 1/4 1/2T 1/4. 1/2 1/1T 1/2. 1/1 2/1T 1/1. 2/1".split(
    " ",
  );
const FREQ = [
  200, 250, 315, 400, 500, 630, 800, 1000, 1250, 1600, 2000, 2500, 3150, 4000,
  5000, 6300, 8000,
];
const unbracket = (s) => s.replace(/ \[(.*)\]$/, "$1");
// Semantic normal form shared by Roland strings and our simulated Rust output.
const norm = (s) =>
  unbracket(s.trim())
    .replace(/msec$/, "ms")
    .replace(/deg$/, "°")
    .replace(/^\+/, "")
    .replace(/(^|\D)0(\d)/g, "$1$2")
    .replace("BYPASSHz", "BYP");
const preTenths = (v) =>
  v < 50
    ? v
    : v < 60
      ? 50 + (v - 50) * 5
      : v < 100
        ? 100 + (v - 60) * 10
        : 500 + (v - 100) * 20;
const fixed = [
  ["Plain", (v) => `${v}`],
  ["Decibels", (v) => `${v}dB`],
  ["Millis", (v) => `${v}ms`],
  ["RateHz", (v) => `${(v * 0.05).toFixed(2)}Hz`],
  ["StepRateHz", (v) => `${((v + 9) * 0.01).toFixed(2)}Hz`],
  ["DegreesX2", (v) => `${v * 2}°`],
  ["FeedbackPercent", (v) => `${2 * v - 98}%`],
  ["Note", (v) => NOTE[v]],
  ["Freq", (v) => (v < 17 ? `${FREQ[v]}Hz` : v === 17 ? "BYP" : "?")],
  [
    "PreDelay",
    (v) => {
      const t = preTenths(v);
      return t < 100 ? `${(t / 10).toFixed(1)}ms` : `${t / 10}ms`;
    },
  ],
  ["EqLowFreq", (v) => ["200Hz", "400Hz"][v]],
  ["EqHighFreq", (v) => ["2000Hz", "4000Hz", "8000Hz"][v]],
  ["EqQ", (v) => ["0.5", "1.0", "2.0", "4.0", "8.0"][v]],
  ["Pan", (v) => (v < 64 ? `L${64 - v}` : v === 64 ? "0" : `${v - 64}R`)],
  ["Balance", (v) => `D${100 - v}:${v}W`],
];
const names = new Map(); // joined list -> static name
let checked = 0;
function unitFor(l, disp) {
  const lo = l.min - 32768,
    want = disp.map(norm);
  const ok = (f) => want.every((w, i) => norm(f(lo + i)) === w);
  for (const [u, f] of fixed) if (ok(f)) return `FxUnit::${u}`;
  const n0 = parseFloat(want[0]),
    n1 = parseFloat(want[1]);
  if (!isNaN(n0) && !isNaN(n1) && want.length > 2) {
    const step = n1 - n0,
      offset = lo - n0 / step,
      suffix = want[0].replace(/^-?[0-9.]+/, "");
    if (
      Number.isInteger(step) &&
      Number.isInteger(offset) &&
      offset !== 0 &&
      ok((v) => `${(v - offset) * step}${suffix}`)
    )
      return `FxUnit::Offset { offset: ${offset}, step: ${step}, suffix: ${JSON.stringify(suffix)} }`;
  }
  if (lo !== 0 || disp.length > 32)
    throw new Error(`no unit for ${l.id}: ${disp.slice(0, 4)}`);
  const list = disp.map(unbracket),
    key = list.join("\u0000");
  if (!names.has(key))
    names.set(key, {
      name: list.join() === "OFF,ON" ? "OFF_ON" : l.id.replace(/^MFX_/, ""),
      list,
    });
  return `FxUnit::Names(${names.get(key).name})`;
}
const consts = T.map((x, id) => {
  const leaves = x.leaf.slice(4),
    lines = [];
  for (let k = 0; k < leaves.length; k++) {
    const l = leaves[k];
    if (l.desc === "_" || l.desc === "") continue; // dummy / hidden slot
    const s = S[l.id];
    const disp = s
      ? Array.from({ length: l.max - l.min + 1 }, (_, i) => s.getString(i))
      : Array.from(
          { length: l.max - l.min + 1 },
          (_, i) => `D${100 - i}:${i}W`,
        ); // EPDLY balance has no stringer
    const m0 = l.desc.match(/^(.*) \((sync sw|msec|Hz|note)\)$/);
    const m =
      m0 &&
      ((m0[2] !== "msec" && m0[2] !== "Hz") ||
        leaves[k - 1]?.desc.endsWith("(sync sw)"))
        ? m0
        : null;
    const label = m0 ? m0[1] : l.desc;
    if (m && m[2] === "sync sw") continue;
    if (m && m[2] === "note") continue;
    const st = (v) => v - 32768;
    let line = `    param(${k}, ${JSON.stringify(label)}, ${st(l.min)}, ${st(l.max)}, ${st(l.init)}, ${unitFor(l, disp)})`;
    if (m) {
      const sw = leaves[k - 1],
        note = leaves[k + 1];
      if (
        !sw.desc.endsWith("(sync sw)") ||
        !note.desc.endsWith("(note)") ||
        note.max - note.min !== 21 ||
        sw.max - sw.min !== 1
      )
        throw new Error(`bad triple ${l.id}`);
      line += `.synced(${st(note.init)}, ${m[2] === "msec" ? "SYNC_MS" : "SYNC_HZ"})`;
      if (st(sw.init) === 1) line += ".note_by_default()";
    }
    lines.push(line + ",");
    checked++;
  }
  return `const ${constName(id)}: &[FxParamDef] = &[\n${lines.join("\n")}\n];\n`;
});
/** A JS string list as the items of a Rust `&[&str]` literal. */
const rsStrs = (list) => list.map((s) => JSON.stringify(s)).join(", ");
const statics = [...names.values()].map(
  ({ name, list }) => `static ${name}: &[&str] = &[${rsStrs(list)}];`,
);
// Control Assign 1-4 (leaves 0-3) pick from one per-type list; value = index.
const controlTargets = T.map((x) => {
  const [first, ...rest] = x.leaf
    .slice(0, 4)
    .map((l) =>
      Array.from({ length: l.max - l.min + 1 }, (_, i) => S[l.id].getString(i)),
    );
  if (rest.some((l) => l.join() !== first.join()))
    throw new Error(`${x.desc}: Control Assign lists differ`);
  return first;
});
const controls =
  "/// Control Assign destinations per type (index = type ID), value = list index.\n" +
  `static MFX_CONTROL_TARGETS: [&[&str]; ${T.length}] = [\n` +
  controlTargets.map((l) => `    &[${rsStrs(l)}],`).join("\n") +
  "\n];\n\n";
const gen =
  `${BEGIN}\n\n${controls}// Display names for list-valued parameters, index = stored value.\n\n${statics.join("\n")}\n\n` +
  consts
    .map((c, id) => `// Type ${id}: ${T[id].desc}\n${c}`)
    .join("\n")
    .replaceAll(
      'FxUnit::Offset { offset: 15, step: 1, suffix: "dB" }',
      "GAIN_DB",
    ) +
  `\n${END}`;
const path = process.argv[2];
const rs = fs.readFileSync(path, "utf8");
const a = rs.indexOf(BEGIN),
  b = rs.indexOf(END);
if (a < 0 || b < a)
  throw new Error(`${path}: missing generated-region markers`);
fs.writeFileSync(path, rs.slice(0, a) + gen + rs.slice(b + END.length));
console.log(`${path}: ${checked} params, ${names.size} name lists`);
